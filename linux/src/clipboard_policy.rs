use crate::model::plain_url;
use regex::Regex;
use sha2::{Digest, Sha256};
use std::sync::OnceLock;

fn private_format_re() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| {
        Regex::new(r"(?i)concealed|transienttype|autogeneratedtype|password|agilebits|ExcludeClipboardContentFromMonitorProcessing|ClipBoardLine\.Internal\.v1")
            .unwrap()
    })
}

pub fn private_clipboard<S: AsRef<str>>(formats: &[S]) -> bool {
    formats
        .iter()
        .any(|f| private_format_re().is_match(f.as_ref()))
}

pub fn valid_sequence(value: u64) -> bool {
    value > 0 && value <= 0xffff_ffff
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ClipboardPayload {
    Text(String),
    Link(String),
    Image(Vec<u8>),
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ClipboardContent {
    pub kind: String,
    pub payload: ClipboardPayload,
    pub sequence: u64,
    pub owned: bool,
    pub fingerprint: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ClipboardReadResult {
    Empty,
    Raced,
    Content(ClipboardContent),
}

pub trait ClipboardEntry {
    fn types(&self) -> Vec<String>;
    fn get_type(&self, mime: &str) -> Result<Vec<u8>, String>;
}

pub trait ClipboardReader {
    type Entry: ClipboardEntry;
    fn read(&self) -> Result<Vec<Self::Entry>, String>;
}

pub fn read_clipboard_content<R, F>(
    clipboard: &R,
    sequence: F,
    marker: &[u8],
    capture_links: bool,
) -> ClipboardReadResult
where
    R: ClipboardReader,
    F: Fn() -> Result<u64, String>,
{
    let Ok(before) = sequence() else {
        return ClipboardReadResult::Empty;
    };
    if !valid_sequence(before) {
        return ClipboardReadResult::Empty;
    }
    let current = || sequence().map(|s| s == before).unwrap_or(false);

    let Ok(entries) = clipboard.read() else {
        return ClipboardReadResult::Empty;
    };
    if entries.is_empty() {
        return ClipboardReadResult::Empty;
    }
    let all_types: Vec<String> = entries.iter().flat_map(|e| e.types()).collect();
    if private_clipboard(&all_types) {
        return ClipboardReadResult::Empty;
    }
    if !current() {
        return ClipboardReadResult::Raced;
    }

    let mut owned = false;
    for entry in &entries {
        for format in entry.types() {
            if format == "web application/x.clipboardline" {
                let Ok(bytes) = entry.get_type(&format) else {
                    return ClipboardReadResult::Empty;
                };
                if bytes.len() != marker.len() {
                    return ClipboardReadResult::Empty;
                }
                if bytes == marker {
                    owned = true;
                }
            }
            if format.contains("CanIncludeInClipboardHistory") {
                let Ok(bytes) = entry.get_type(&format) else {
                    return ClipboardReadResult::Empty;
                };
                if bytes.len() != 4 {
                    return ClipboardReadResult::Empty;
                }
                let val = u32::from_le_bytes([bytes[0], bytes[1], bytes[2], bytes[3]]);
                if val == 0 {
                    return ClipboardReadResult::Empty;
                }
            }
        }
    }
    if owned {
        return ClipboardReadResult::Empty;
    }
    if !current() {
        return ClipboardReadResult::Raced;
    }

    let image_entry = entries
        .iter()
        .find(|item| item.types().iter().any(|t| t == "image/png"));
    let (kind, payload, raw_bytes) = if let Some(img) = image_entry {
        let Ok(bytes) = img.get_type("image/png") else {
            return ClipboardReadResult::Empty;
        };
        if bytes.len() > 64 * 1024 * 1024 {
            return ClipboardReadResult::Empty;
        }
        (
            "image".to_string(),
            ClipboardPayload::Image(bytes.clone()),
            bytes,
        )
    } else {
        let Some(text_entry) = entries
            .iter()
            .find(|item| item.types().iter().any(|t| t == "text/plain"))
        else {
            return ClipboardReadResult::Empty;
        };
        let Ok(bytes) = text_entry.get_type("text/plain") else {
            return ClipboardReadResult::Empty;
        };
        if bytes.len() > 1024 * 1024 {
            return ClipboardReadResult::Empty;
        }
        let Ok(mut decoded) = String::from_utf8(bytes.clone()) else {
            return ClipboardReadResult::Empty;
        };
        if let Some(stripped) = decoded.strip_prefix('\u{feff}') {
            decoded = stripped.to_string();
        }
        if decoded.is_empty() || !decoded.chars().any(|c| !c.is_whitespace()) {
            return ClipboardReadResult::Empty;
        }
        if capture_links {
            if let Some(url) = plain_url(&decoded) {
                ("link".to_string(), ClipboardPayload::Link(url), bytes)
            } else {
                ("text".to_string(), ClipboardPayload::Text(decoded), bytes)
            }
        } else {
            ("text".to_string(), ClipboardPayload::Text(decoded), bytes)
        }
    };

    if !current() {
        return ClipboardReadResult::Raced;
    }

    let mut hasher = Sha256::new();
    hasher.update(&raw_bytes);
    let fingerprint = format!("{}:{}", kind, hex::encode(hasher.finalize()));

    ClipboardReadResult::Content(ClipboardContent {
        kind,
        payload,
        sequence: before,
        owned: false,
        fingerprint,
    })
}

pub fn repeated_generation(last_sequence: &mut Option<u64>, content_sequence: u64) -> bool {
    if *last_sequence == Some(content_sequence) {
        return true;
    }
    *last_sequence = Some(content_sequence);
    false
}
